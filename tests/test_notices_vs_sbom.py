"""check_notices_vs_sbom.py: the staged notices must describe exactly the components of the final SBOM."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = ROOT / "packaging" / "notices"


def _load(name):
    spec = importlib.util.spec_from_file_location(name, N / f"{name}.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


gen = _load("generate_notices")
chk = _load("check_notices_vs_sbom")
stage = _load("stage_licenses")


def sbom(path: Path, comps):
    path.write_text(json.dumps({"bomFormat": "CycloneDX", "specVersion": "1.5", "components": [
        {"type": "library", "name": n, "version": v, "purl": f"pkg:pypi/{n}@{v}"} for n, v in comps]}))
    return path


def build(tmp: Path, comps):
    pass1 = sbom(tmp / "pass1.json", comps)
    out = tmp / "out"
    gen.run(pass1, [], [], gen.HERE / "texts", None, out, "t", [])
    dest = tmp / "licenses"
    assert stage.stage(out, dest) == []
    return out, dest


def test_matching_sets_pass(tmp_path):
    out, dest = build(tmp_path, [("alpha", "1.0"), ("beta", "2.0")])
    final = sbom(tmp_path / "final.json", [("alpha", "1.0"), ("beta", "2.0")])
    assert chk.check(final, out / "notices-report.json", dest, []) == []


def test_a_component_added_after_the_notices_were_made_is_reported(tmp_path):
    out, dest = build(tmp_path, [("alpha", "1.0")])
    final = sbom(tmp_path / "final.json", [("alpha", "1.0"), ("gamma", "3.0")])
    errs = chk.check(final, out / "notices-report.json", dest, [])
    assert any("gamma" in e and "not in the notices" in e for e in errs), errs


def test_phantom_version_drift_and_exclusion(tmp_path):
    out, dest = build(tmp_path, [("alpha", "1.0"), ("beta", "2.0")])
    final = sbom(tmp_path / "final.json", [("alpha", "1.1")])
    errs = chk.check(final, out / "notices-report.json", dest, [])
    assert any("beta" in e and "not in the final SBOM" in e for e in errs)
    assert any("version differs" in e and "alpha" in e for e in errs)
    # an excluded component is ignored on both sides
    final2 = sbom(tmp_path / "final2.json", [("alpha", "1.0"), ("beta", "2.0"), ("knowledge-frontier", "0.1.0")])
    assert chk.check(final2, out / "notices-report.json", dest, ["knowledge-frontier"]) == []


def test_an_edited_staged_folder_or_a_foreign_sbom_digest_is_reported(tmp_path):
    out, dest = build(tmp_path, [("alpha", "1.0")])
    final = sbom(tmp_path / "final.json", [("alpha", "1.0")])
    (dest / "THIRD_PARTY_NOTICES.txt").write_text("edited\n")
    errs = chk.check(final, out / "notices-report.json", dest, [])
    assert any("differs from LICENSES-MANIFEST.json" in e for e in errs), errs
    assert any("was not generated from the SBOM" in e for e in errs), errs


def _with_embedded_folder(path: Path, comps, dest: Path, tamper=False):
    import hashlib
    props = [{"name": "redevops:role", "value": "first-party licence/notice text files generated by packaging/notices"}]
    for p in sorted(dest.iterdir()):
        h = hashlib.sha256(p.read_bytes()).hexdigest()
        props.append({"name": f"redevops:sha256:Licenses/{p.name}", "value": ("0" * 64) if tamper and p.name == "LICENSING.md" else h})
    doc = {"bomFormat": "CycloneDX", "specVersion": "1.5", "components": [
        {"type": "library", "name": n, "version": v, "purl": f"pkg:pypi/{n}@{v}"} for n, v in comps] + [
        {"type": "data", "name": "Licenses folder (embedded)", "properties": props}]}
    path.write_text(json.dumps(doc))
    return path


def test_the_embedded_licenses_folder_is_first_party_and_must_equal_the_staged_folder(tmp_path):
    out, dest = build(tmp_path, [("alpha", "1.0")])
    ok = _with_embedded_folder(tmp_path / "f1.json", [("alpha", "1.0")], dest)
    assert chk.check(ok, out / "notices-report.json", dest, []) == []
    bad = _with_embedded_folder(tmp_path / "f2.json", [("alpha", "1.0")], dest, tamper=True)
    errs = chk.check(bad, out / "notices-report.json", dest, [])
    assert any("LICENSING.md" in e and "embedded copy" in e for e in errs), errs
