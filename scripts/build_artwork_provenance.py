#!/usr/bin/env python3
"""Generate (or --check) docs/legal/ARTWORK_PROVENANCE.md: the provenance record of the artwork that ships in the desktop product.

It records FACTS only: which files are the output of which generator script, the SHA-256 of the generator and of every output, how to regenerate and which
test enforces equality. It makes NO statement about authorship or rights, and no attestation: whether anyone holds rights in the output of a script written
by an AI coding agent is a legal question that stays open (counsel question Q28/Q29). Standard library only.
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "legal" / "ARTWORK_PROVENANCE.md"
HERO = "agentic_os/projects_ui/hero.jpg"
HERO_LAST = "8b1470ffde8d64990b7be1d9759c971fa0f3169f4cfb1884968645de6961a7fb"
ART_REL = "packaging/ui-artifacts/projects-ui-root-ea9e53e5-nohero.tgz"
ICON_DIRS = ("deploy/launcher/src-tauri/icons", "deploy/desktop-shell-main/src-tauri/icons")
ICON_FILES = ("32x32.png", "128x128.png", "128x128@2x.png", "icon.png", "icon.icns", "icon.ico")
UNVERIFIED_GLOBS = ("apps/social-autopilot/reel/assets/hero.jpg", "deploy/assets/repos/")


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def tracked(prefix: str) -> list[str]:
    q = subprocess.run(["git", "-C", str(ROOT), "ls-files", prefix], capture_output=True, text=True, env={"PATH": "/usr/bin:/bin:/opt/homebrew/bin"}, check=True)
    return sorted(q.stdout.split("\n")[:-1])


def art_state() -> str:
    import tarfile
    p = ROOT / ART_REL
    if not p.is_file():
        return "**MISSING**"
    with tarfile.open(p, "r:gz") as t:
        names = sorted(m.name for m in t.getmembers() if m.isfile())
    img = [n for n in names if n.lower().endswith((".jpg", ".jpeg", ".png", ".gif", ".webp", ".svg", ".ico"))]
    return f"sha256 `{sha(p)}`, {len(names)} members, " + ("no image member" if not img else f"**IMAGE MEMBERS: {img}**")


def render() -> str:
    L = ["# Artwork provenance (generated by scripts/build_artwork_provenance.py; do not edit)", "",
         "This file records facts about the artwork of the desktop product. It makes no statement about authorship or rights and it is not an attestation:",
         "rights in the output of a script written by an AI coding agent are a legal question that stays open (counsel questions Q28 and Q29, decisions D-LIC-8 and D-LIC-11).", "",
         "## 1. The Projects UI hero image: REMOVED from the product (D-LIC-8, option c)", "",
         "The owner decided on 2026-11-11 to remove the image whose distribution rights cannot be established; no authorship or ownership attestation is made for an image that is not distributed.", "",
         "| Item | Value |", "|---|---|",
         "| File `agentic_os/projects_ui/hero.jpg` | " + ("absent (checked now)" if not (ROOT / HERO).exists() else "**PRESENT: this record is wrong**") + " |",
         f"| Last shipped bytes (history only) | SHA-256 `{HERO_LAST}` |",
         "| Generator script `scripts/make_neutral_hero.py` | " + ("absent (removed with the image; it stays in git history, commit e9742de)" if not (ROOT / "scripts/make_neutral_hero.py").exists() else "**PRESENT**") + " |",
         "| Pinned UI artifact | `" + ART_REL + "`, " + art_state() + " |",
         "| Superseded artifact (history, not shipped) | `packaging/ui-artifacts/projects-ui-root-ea9e53e5.tgz`, sha256 `b202abc5e2c2cf63fa26854a1d299d71e78267d18f4201bfc745e5c218517b73`, the same build output plus the image |",
         "| Earlier image (no longer shipped) | an image whose C2PA metadata named a third-party generator (\"Black Forest Labs API\"); not retained |",
         "| Visible effect | the built UI contains a sample-data item with the path `/hero.jpg` as its preview; with the image removed that picture cannot load (the server answers 404); how the sample view then looks has not been inspected visually. Runtime data from the API carries no preview. |", "",
         "## 2. The launcher icons", "",
         f"Generator: `scripts/make_neutral_icons.py` (SHA-256 `{sha(ROOT / 'scripts/make_neutral_icons.py')}`), Python standard library only; a rounded square with a slate gradient, one pale diamond and one round cut-out; no letters, no fonts, no model output.",
         "Enforcement: `tests/test_launcher_icons.py` (files equal the generator output; the previous artwork is nowhere in the repository).", "",
         "| File | " + " | ".join(f"`{d}`" for d in ICON_DIRS) + " |", "|---|" + "---|" * len(ICON_DIRS)]
    for f in ICON_FILES:
        cells = []
        for d in ICON_DIRS:
            p = ROOT / d / f
            cells.append(f"`{sha(p)}`" if p.is_file() else "(absent)")
        L.append(f"| `{f}` | " + " | ".join(cells) + " |")
    L += ["", "## 3. Image files with NO provenance record in this repository (not covered by any statement here)", "",
          "These are not part of the desktop product's shipped set. They are listed so that nothing is presumed resolved.", "", "| File | SHA-256 |", "|---|---|"]
    for g in UNVERIFIED_GLOBS:
        for f in tracked(g):
            L.append(f"| `{f}` | `{sha(ROOT / f)}` |")
    L += ["", "## 4. How to regenerate", "", "`python scripts/make_neutral_icons.py`, then `python scripts/build_artwork_provenance.py` (the hero image has no generator any more).", ""]
    return "\n".join(L)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("artwork provenance record is current" if ok else "docs/legal/ARTWORK_PROVENANCE.md is missing or stale: run scripts/build_artwork_provenance.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
