#!/usr/bin/env python3
"""Generate (or --check) docs/legal/ARTWORK_PROVENANCE.md: the provenance record of the artwork that ships in the desktop product.

It records FACTS only: which files are the output of which generator script, the SHA-256 of the generator and of every output, how to regenerate and which
test enforces equality. It makes NO statement about authorship or rights, and no attestation: whether anyone holds rights in the output of a script written
by an AI coding agent is a legal question that stays open (counsel question Q28/Q29). Standard library only.
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "legal" / "ARTWORK_PROVENANCE.md"
HERO = "agentic_os/projects_ui/hero.jpg"
ICON_DIRS = ("deploy/launcher/src-tauri/icons", "deploy/desktop-shell-main/src-tauri/icons")
ICON_FILES = ("32x32.png", "128x128.png", "128x128@2x.png", "icon.png", "icon.icns", "icon.ico")
UNVERIFIED_GLOBS = ("apps/social-autopilot/reel/assets/hero.jpg", "deploy/assets/repos/")


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def tracked(prefix: str) -> list[str]:
    q = subprocess.run(["git", "-C", str(ROOT), "ls-files", prefix], capture_output=True, text=True, env={"PATH": "/usr/bin:/bin:/opt/homebrew/bin"}, check=True)
    return sorted(q.stdout.split("\n")[:-1])


def render() -> str:
    L = ["# Artwork provenance (generated by scripts/build_artwork_provenance.py; do not edit)", "",
         "This file records facts about the artwork that ships in the desktop product. It makes no statement about authorship or rights and it is not an attestation:",
         "rights in the output of a script written by an AI coding agent are a legal question that stays open (counsel questions Q28 and Q29, decisions D-LIC-8 and D-LIC-11).", "",
         "## 1. The Projects UI hero image", "",
         "| Item | Value |", "|---|---|",
         f"| File | `{HERO}` |", f"| SHA-256 | `{sha(ROOT / HERO)}` |",
         f"| Generator | `scripts/make_neutral_hero.py` (SHA-256 `{sha(ROOT / 'scripts/make_neutral_hero.py')}`) |",
         "| Content | a gradient and geometric shapes drawn with Pillow; no text, no fonts, no photograph, no model output, no embedded metadata |",
         "| Replaced | an earlier image whose C2PA metadata named a third-party generator (\"Black Forest Labs API\"); it is no longer shipped and is not retained |",
         "| Enforcement | `tests/test_hero_asset.py` (the file is the generator's deterministic output) |",
         "| Written by | an AI coding agent (commit e9742de); see the component inventory flag for AI-authored commits |", "",
         "## 2. The launcher icons", "",
         f"Generator: `scripts/make_neutral_icons.py` (SHA-256 `{sha(ROOT / 'scripts/make_neutral_icons.py')}`), Python standard library only; a rounded square with a slate gradient, one pale diamond and one round cut-out; no letters, no fonts, no model output.",
         "Enforcement: `tests/test_launcher_icons.py` (files equal the generator output; the previous artwork is nowhere in the repository).", "",
         "| File | " + " | ".join(f"`{d}`" for d in ICON_DIRS) + " |", "|---|" + "---|" * len(ICON_DIRS)]
    for f in ICON_FILES:
        cells = []
        for d in ICON_DIRS:
            p = ROOT / d / f
            cells.append(f"`{sha(p)}`" if p.is_file() else "(absent)")
        L.append(f"| `{f}` | " + " | ".join(cells) + " |")
    L += ["", "## 3. Image files with NO provenance record in this repository (not covered by any statement here)", "",
          "These are not part of the desktop product's shipped set. They are listed so that nothing is presumed resolved.", "", "| File | SHA-256 |", "|---|---|"]
    for g in UNVERIFIED_GLOBS:
        for f in tracked(g):
            L.append(f"| `{f}` | `{sha(ROOT / f)}` |")
    L += ["", "## 4. How to regenerate", "", "`python scripts/make_neutral_hero.py` and `python scripts/make_neutral_icons.py`, then `python scripts/build_artwork_provenance.py`.", ""]
    return "\n".join(L)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("artwork provenance record is current" if ok else "docs/legal/ARTWORK_PROVENANCE.md is missing or stale: run scripts/build_artwork_provenance.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
