#!/usr/bin/env python3
"""Generate the shipped-component SBOM (CycloneDX 1.5) from the BUILT artifacts.

  python -I packaging/sbom/generate_sbom.py --sidecar packaging/dist/redevops-sidecar \
      --wheelhouse packaging/wheelhouse --inventory-env <freeze-venv python> \
      --build-manifest packaging/dist/build-manifest.json --git-pins packaging/git-pins.json \
      --cargo-manifest deploy/launcher/src-tauri/Cargo.toml --cargo-lock deploy/launcher/src-tauri/Cargo.lock \
      --launcher-bin <launcher binary> --tauri-conf deploy/launcher/src-tauri/tauri.conf.json --out packaging/dist/sbom

Run it with the freeze venv's python (PyInstaller importable) when reading an executable.
Writes: sbom.cdx.json, archive-attribution.json (every PKG entry / PYZ module -> component, with sha256),
sbom-inputs.json (what the SBOM was derived from).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sbom import cyclonedx, rustsbom  # noqa: E402
from sbom.analyze import Comp, FIRST_PARTY, declared_licence  # noqa: E402
from sbom.common_cli import add_input_args, run_analysis  # noqa: E402

GENERATOR_VERSION = "1"


def first_party_refs(res, pins: dict, manifest: dict) -> None:
    by = {p["name"].replace("_", "-").lower(): p for p in pins.get("dependencies", [])}
    for key, c in res.comps.items():
        if not key.startswith("pypi:"):
            continue
        n = key.split(":", 1)[1]
        if n not in FIRST_PARTY:
            continue
        p = by.get(n)
        if p:
            repo = p["url"].removesuffix(".git").rsplit("/", 1)[-1]
            c.purl = f"pkg:github/redevops-io/{repo}@{p['commit']}"
            c.refs["vcs"] = f"git+{p['url']}@{p['commit']}"
            c.props.update({"redevops:git-tag": p["tag"], "redevops:git-tag-object": p["tag_object"], "redevops:git-commit": p["commit"]})
            c.refs.pop("distribution", None)
        elif n == "agentic-os":
            src = manifest.get("source", {})
            if src.get("commit"):
                c.purl = f"pkg:github/redevops-io/agentic-os@{src['commit']}"
                c.refs["vcs"] = f"git+https://github.com/redevops-io/agentic-os@{src['commit']}"
                c.props["redevops:git-commit"] = src["commit"]
                c.props["redevops:git-tree"] = src.get("tree", "")
                if src.get("dirty_files"):
                    c.props["redevops:source-tree-dirty"] = f"{src['dirty_files']} uncommitted/untracked files at build time"
        c.props["redevops:source-offer"] = "see packaging/SOURCE-OFFER.md (generated by packaging/sbom/generate_source_offer.py)"


def rust_components(a, comps: list[Comp], launcher: Comp | None) -> tuple[list[Comp], dict[str, str]]:
    notes: dict[str, str] = {}
    if not (a.cargo_manifest or a.cargo_metadata_json):
        return [], notes
    meta = json.loads(Path(a.cargo_metadata_json).read_text()) if a.cargo_metadata_json else rustsbom.cargo_metadata(a.cargo_manifest, a.cargo_target)
    sums = rustsbom.lock_checksums(a.cargo_lock) if a.cargo_lock else {}
    out = []
    for cr in rustsbom.crates(meta, sums):
        c = Comp(key=f"cargo:{cr['name']}@{cr['version']}", name=cr["name"], version=cr["version"],
                 purl=f"pkg:cargo/{cr['name']}@{cr['version']}", scope=cr["scope"],
                 licence=({"expression": cr["licence"], "source": "Cargo.toml license of the crate (crates.io metadata)"} if cr["licence"] else None),
                 evidence=[f"cargo metadata --locked --filter-platform {a.cargo_target} on Cargo.lock"])
        if cr["checksum"]:
            c.hashes["SHA-256"] = cr["checksum"]
            c.props["redevops:hash-of"] = "the .crate archive on crates.io (Cargo.lock checksum)"
        if cr["registry"]:
            c.refs["distribution"] = f"https://crates.io/api/v1/crates/{cr['name']}/{cr['version']}/download"
        if cr["repository"]:
            c.refs["vcs"] = cr["repository"]
        if cr["licence_file"] and not cr["licence"]:
            c.props["redevops:licence-file"] = cr["licence_file"]
        if cr["proc_macro"]:
            c.props["redevops:rust-kind"] = "proc-macro (runs at compile time; not linked into the launcher)"
        c.props["redevops:cargo-source"] = cr["source"] or "path"
        c.shipped_in.add("launcher" if cr["scope"] == "required" else "build-time-only")
        if cr["scope"] != "required":
            c.props["redevops:scope-note"] = "reachable only through build-script dependency edges: compiled on the build host, not linked into the launcher"
        out.append(c)
    lc = rustsbom.launcher_crate(meta)
    if launcher:
        launcher.licence = {"expression": lc["licence"], "source": "Cargo.toml license of redevops-launcher"} if lc["licence"] else None
        if a.cargo_lock:   # no absolute path: the SBOM must not depend on where the tree was checked out
            launcher.props["redevops:cargo-lock-sha256"] = hashlib.sha256(Path(a.cargo_lock).read_bytes()).hexdigest()
    notes["rust-target"] = a.cargo_target
    return out, notes


def platform_notes(triple: str) -> list[Comp]:
    out = []
    if "apple-darwin" in triple:
        out.append(Comp(key="platform:wkwebview", name="WKWebView (macOS system WebKit)", version=None, kind="platform", scope="excluded",
                        evidence=["Tauri 2 on macOS renders with the system WebKit; the launcher links only system frameworks (audit: otool -L)"],
                        limitations=["not shipped: provided by macOS; version is the OS's"]))
    if "windows" in triple:
        out.append(Comp(key="platform:webview2", name="Microsoft Edge WebView2 Runtime", version=None, kind="platform", scope="excluded",
                        evidence=["Tauri 2 on Windows needs WebView2; tauri.conf.json sets no bundle.windows.webviewInstallMode, so the Tauri default applies"],
                        limitations=["not bundled; the installer may download Microsoft's bootstrapper at install time (derived from the Tauri schema, UNVERIFIED by observation)"]))
    if "linux" in triple:
        out.append(Comp(key="platform:webkit2gtk", name="WebKitGTK (system)", version=None, kind="platform", scope="excluded",
                        evidence=["Tauri 2 on Linux uses the system WebKitGTK"], limitations=["not shipped: package dependency of the .deb/AppImage host"]))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_input_args(ap)
    ap.add_argument("--out", required=True)
    ap.add_argument("--timestamp", help="ISO timestamp (default: SOURCE_DATE_EPOCH / commit time of the build manifest / now)")
    a = ap.parse_args(argv)
    arc, inv, res, facts, manifest = run_analysis(a)
    pins = json.loads(Path(a.git_pins).read_text()) if a.git_pins else {}
    first_party_refs(res, pins, manifest)
    comps = list(res.comps.values())

    # launcher
    launcher = None
    tauri_ver = None
    if a.tauri_conf:
        tauri_ver = json.loads(Path(a.tauri_conf).read_text()).get("version")
    if a.launcher_bin or a.cargo_manifest or a.cargo_metadata_json:
        launcher = Comp(key="launcher", name="agentic-apps launcher (redevops-launcher)", version=tauri_ver, kind="application",
                        purl=f"pkg:generic/redevops-launcher@{tauri_ver}" if tauri_ver else None)
        launcher.shipped_in.add("launcher")
        launcher.evidence.append("tauri.conf.json / Cargo.toml of the launcher crate")
        if a.launcher_bin and Path(a.launcher_bin).is_file():
            data = Path(a.launcher_bin).read_bytes()
            launcher.hashes["SHA-256"] = hashlib.sha256(data).hexdigest()
            paths = rustsbom.crate_paths_in_binary(data)
            launcher.props["redevops:crate-path-strings-in-binary"] = str(len(paths))
            launcher.evidence.append(f"built binary {Path(a.launcher_bin).name} hashed; {len(paths)} crate source-path strings found in it (lower bound of linked crates)")
        comps.append(launcher)
    crates, notes = rust_components(a, comps, launcher)
    comps += crates
    if launcher or crates:
        comps += platform_notes(a.cargo_target)

    # unattributed / problems become limitations the reader cannot miss
    limitations = dict(res.limitations)
    for i, u in enumerate(res.unattributed):
        limitations[f"UNATTRIBUTED-{i + 1:03d}"] = f"archive entry with no owning component: {u}"
    for i, p in enumerate(res.problems):
        limitations[f"PROBLEM-{i + 1:03d}"] = p
    if a.cargo_manifest or a.cargo_metadata_json:
        limitations["L-LAUNCHER-CRATES"] = ("Crates are those cargo resolves for the build target from Cargo.lock; crates.io checksums are of the .crate archives. "
                                            "The binary is cross-checked by crate source-path strings (a lower bound), see verify_sbom.py.")

    src = manifest.get("source", {})
    ts = a.timestamp or (time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(int(os.environ.get("SOURCE_DATE_EPOCH") or src.get("commit_time_epoch") or time.time()))))
    root_ver = tauri_ver or (inv.get("agentic-os") or {}).get("version")
    root = {"type": "application", "bom-ref": "rdo:product", "name": "Agentic Apps (native build)", "version": root_ver,
            "properties": [{"name": "redevops:source-commit", "value": src.get("commit", "unknown")},
                           {"name": "redevops:source-tree", "value": src.get("tree", "unknown")},
                           {"name": "redevops:archive-source", "value": arc.source},
                           {"name": "redevops:archive-sha256", "value": arc.source_sha256 or ""}]}
    deps: dict[str, list[str]] = {}
    sidecar_refs = [cyclonedx.bom_ref(c.key) for c in comps if any(s.startswith("sidecar") for s in c.shipped_in) and c.key != "sidecar"]
    deps["rdo:sidecar"] = sidecar_refs
    launcher_refs = [cyclonedx.bom_ref(c.key) for c in comps if "launcher" in c.shipped_in and c.key != "launcher"]
    if launcher:
        deps["rdo:launcher"] = launcher_refs
    deps["rdo:product"] = [r for r in ("rdo:sidecar", "rdo:launcher" if launcher else None) if r]
    notes["archive-entries"] = f"PKG {len(arc.pkg)}, PYZ {len(arc.pyz)}"
    notes["generation-method"] = ("Derived from the BUILT archive (PyInstaller CArchive/PYZ), the installed wheels, the build venv's metadata and the launcher's "
                                  "Cargo.lock graph; not from a lock file alone. It is incomplete by construction: see the limitation entries.")
    bom = cyclonedx.build(root, comps, limitations, ts, {"generator": GENERATOR_VERSION}, deps, notes)

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "sbom.cdx.json").write_text(json.dumps(bom, indent=2, sort_keys=True) + "\n")
    attrib = {}
    for k, key in sorted(res.attribution.items()):
        kind, name = k.split(":", 1)
        data = arc.read(name) if kind == "pkg" else arc.pyz_read(name)
        attrib[k] = {"component": key, **({"sha256": hashlib.sha256(data).hexdigest(), "size": len(data)} if data else {})}
    (out / "archive-attribution.json").write_text(json.dumps({"archive": arc.source, "archive_sha256": arc.source_sha256,
                                                              "unattributed": res.unattributed, "entries": attrib}, indent=1, sort_keys=True) + "\n")
    inputs = {"archive": arc.source, "archive_sha256": arc.source_sha256, "wheelhouse": [v["wheel_sha256"] for v in inv.values() if v.get("wheel_sha256")],
              "facts": a.facts, "has_bytes": arc.has_bytes, "cargo_lock": a.cargo_lock}
    (out / "sbom-inputs.json").write_text(json.dumps(inputs, indent=1, sort_keys=True) + "\n")
    n_un = len(res.unattributed)
    print(f"SBOM: {len(bom['components'])} components -> {out / 'sbom.cdx.json'}; attribution of {len(attrib)} archive entries; unattributed: {n_un}")
    return 1 if (n_un or res.problems) else 0


if __name__ == "__main__":
    raise SystemExit(main())
