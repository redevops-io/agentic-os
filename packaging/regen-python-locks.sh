#!/usr/bin/env bash
# Regenerate the hash-locked Python requirement files for every build platform.
#   packaging/locks/requirements-<os>.lock   shipped third-party wheels   (from requirements.in)
#   packaging/locks/build-tools-<os>.lock    PyInstaller + its dependencies (from build-tools.in)
#   packaging/locks/build-backends-<os>.lock pip/setuptools/wheel/hatchling (from build-backends.in)
#   packaging/locks/pip.lock                 pip only (freeze venv)
# Needs network (PyPI) and uv. Resolution is bounded by LOCK_EXCLUDE_NEWER (toolchain.env), so
# re-running it later yields the same pins. Cross-platform: uv resolves for a target platform
# without running on it.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
set -a; . "$HERE/toolchain.env"; set +a
OUT="$HERE/locks"; mkdir -p "$OUT"
PYV="${PYTHON_VERSION%.*}"   # 3.12
declare_platforms() { printf '%s\n' macos:aarch64-apple-darwin windows:x86_64-pc-windows-msvc linux:x86_64-unknown-linux-gnu; }
compile() { # <in-file> <out-file> <uv-platform>
  uv pip compile "$1" --python-version "$PYV" --python-platform "$3" --generate-hashes \
     --exclude-newer "$LOCK_EXCLUDE_NEWER" --no-header --quiet -o "$2"
}
for spec in $(declare_platforms); do
  os="${spec%%:*}"; plat="${spec##*:}"
  for kind in requirements build-tools build-backends; do
    f="$HERE/$kind.in"
    compile "$f" "$OUT/$kind-$os.lock.tmp" "$plat"
    { echo "# GENERATED by packaging/regen-python-locks.sh - do not edit."
      echo "# uv $(uv --version | cut -d' ' -f2); python $PYV; platform $plat; --exclude-newer $LOCK_EXCLUDE_NEWER"
      echo "# input: packaging/$kind.in"
      cat "$OUT/$kind-$os.lock.tmp"; } > "$OUT/$kind-$os.lock"
    rm -f "$OUT/$kind-$os.lock.tmp"
  done
done
compile "$HERE/pip.in" "$OUT/pip.lock.tmp" aarch64-apple-darwin
{ echo "# GENERATED by packaging/regen-python-locks.sh - do not edit. pip is a pure wheel: one lock for all OS."
  cat "$OUT/pip.lock.tmp"; } > "$OUT/pip.lock"; rm -f "$OUT/pip.lock.tmp"
echo "locks written to $OUT"
