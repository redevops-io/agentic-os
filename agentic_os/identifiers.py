"""The shared IDENTIFIER CONTRACT: what a principal, role, app, user, tenant or grant name may contain.

An identifier is valid when it is a non-empty ``str`` with

* no leading or trailing Unicode ``White_Space``;
* no Unicode control (``Cc``), format (``Cf``), surrogate (``Cs``), unassigned (``Cn``, which includes the noncharacters), private-use (``Co``),
  line-separator (``Zl``) or paragraph-separator (``Zp``) code point ANYWHERE, and none of the bidirectional formatting controls (U+061C, U+200E/F, U+202A..202E, U+2066..2069).

There is NO case folding and NO Unicode normalization: ``é`` (U+00E9) and ``e`` + U+0301 are two different identifiers, and so are two ids that
only look alike; comparison everywhere is exact. Non-ASCII letters, combining marks and plain emoji stay valid
(a ZWJ emoji sequence contains the format character U+200D and is therefore NOT valid).

The forbidden code points come from ONE generated table, ``identifier_ranges.json`` (Unicode 17.0.0, generated by
``scripts/generate_identifier_ranges.py``; see ``docs/IDENTIFIER_CONTRACT.md`` and ``identifier_ranges.provenance.json``): this module never asks
Python's ``unicodedata`` (the Unicode version of the interpreter must not decide whether an id is valid, or two runtimes would disagree about the
same principal). The table is data derived from the public Unicode Character Database (Unicode License v3). It lists ``forbidden`` (Cc, Cf, Cs, Cn,
Co, Zl, Zp and the bidi controls) and ``white_space`` (the Unicode property, used only for the leading/trailing rule). U+2028 / U+2029 and
private-use code points are rejected anywhere; the generator's ``FORBIDDEN_CATEGORIES`` constant is the single switch for that set.
"""
from __future__ import annotations

import hashlib
import json
from bisect import bisect_right
from pathlib import Path

_BYTES = Path(__file__).with_name("identifier_ranges.json").read_bytes()
_TABLE = json.loads(_BYTES.decode("utf-8"))
if _TABLE.get("schema") != 1:              # a table this code does not understand must stop the process, not loosen the rule
    raise RuntimeError("identifier_ranges.json has an unsupported schema")
UNICODE_VERSION: str = _TABLE["unicode_version"]
FILE_SHA256: str = hashlib.sha256(_BYTES).hexdigest()           # pinned by tests/test_identifier_contract.py
BIDI_CONTROLS = frozenset(cp for lo, hi in _TABLE["bidi_controls"] for cp in range(lo, hi + 1))

# ``forbidden`` = Cc + Cf + Cs + Cn + Co + Zl + Zp + the bidi controls, merged, inclusive [lo, hi] (the generator's ``FORBIDDEN_CATEGORIES`` constant is
# the one switch for which categories are in it); ``white_space`` = the Unicode White_Space property, used only for the leading/trailing rule.
_REJECTED = [tuple(r) for r in _TABLE["forbidden"]]
_LOS = [lo for lo, _ in _REJECTED]
_HIS = [hi for _, hi in _REJECTED]
WHITE_SPACE_RANGES = tuple(tuple(r) for r in _TABLE["white_space"])
_WS_LOS = [lo for lo, _ in WHITE_SPACE_RANGES]
_WS_HIS = [hi for _, hi in WHITE_SPACE_RANGES]


def is_forbidden_code_point(cp: int) -> bool:
    i = bisect_right(_LOS, cp) - 1
    return i >= 0 and cp <= _HIS[i]


def is_white_space(ch: str) -> bool:
    cp = ord(ch)
    i = bisect_right(_WS_LOS, cp) - 1
    return i >= 0 and cp <= _WS_HIS[i]


def identifier_problem(v) -> str | None:
    """Why ``v`` is not a valid identifier (never echoing it), or None when it is valid."""
    if not isinstance(v, str):
        return "not a string"
    if not v:
        return "empty"
    if v.isascii():                       # fast path: printable ASCII only; a leading or trailing space is White_Space
        if not v.isprintable():
            return "contains a control character"
        if v[0] == " " or v[-1] == " ":
            return "has leading or trailing white space"
        return None
    if is_white_space(v[0]) or is_white_space(v[-1]):
        return "has leading or trailing white space"
    for ch in v:
        if is_forbidden_code_point(ord(ch)):
            return ("contains a control, format, surrogate, unassigned (including noncharacter), private-use, line-separator, paragraph-separator or "
                    "bidirectional-control character")
    return None


def valid_identifier(v) -> bool:
    return identifier_problem(v) is None


def absent(v) -> bool:
    """An absent identity field: exactly the empty string. A string made only of White_Space is NOT absent: it is a present value that is not a
    valid identifier, so it invalidates the principal (the shared contract: valid means non-empty and no leading/trailing White_Space)."""
    return isinstance(v, str) and v == ""
