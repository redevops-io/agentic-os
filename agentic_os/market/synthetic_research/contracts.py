"""Contracts for synthetic buyer research. Every object is frozen, JSON-serialisable and ``synthetic=True``.

Design rules (see docs/SYNTHETIC_RESEARCH.md):

* ``synthetic`` is not a switch: constructing any of these objects with ``synthetic=False`` raises. There is no
  conversion to a first-party record, an ``OutcomeEvent`` or a ledger row, and nothing here imports those types.
* Provenance is explicit and local to the study: hashes of the persona frame, the source snapshots, the variants,
  the prompts and the anchor packs, plus model id, parameters and seeds. The first slice is deliberately
  self-contained; ``SourceSnapshot.business_object_ref`` / ``SyntheticResponse.evidence_refs`` are plain strings
  that may carry a ``BusinessObject`` id or ``SearchObservation`` key from ``integrations/business`` /
  ``content/search_signals`` without importing them (linking, not duplicating).
* Persona weights are HYPOTHETICAL stratification weights, never market-sampling weights. Price scenarios are
  HYPOTHESES, never measured willingness to pay.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import asdict, dataclass, field, fields, is_dataclass
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

SCHEMA_VERSION = "synthetic-research/1"

CONSTRUCTS = ("purchase_intent", "trial_intent", "relevance", "trust")
# status labels exactly as a page may state them; "unknown" when the page does not say
STATUS_LABELS = ("planned", "preview", "demo", "sample-data", "available", "production-verified", "unknown")

DISCLAIMERS = (
    "Synthetic, unvalidated hypotheses generated by language-model respondents; not customer research.",
    "Not a conversion, demand, willingness-to-pay or ranking prediction; no number here is a measured rate.",
    "Anchors are LOCAL packs authored for this project, not the anchor sets of the SSR paper (which are not "
    "published); parity with the paper's figures is not tested and none is claimed.",
    "Personas are generic archetypes built from a configurable sampling frame; stratification weights are "
    "hypothetical and are not market-sampling weights.",
    "Findings must be validated with human interviews and A/B tests before any decision; synthetic output is "
    "never first-party evidence and is never written to an outcome store or the first-party ledger.",
)

FIDELITY_STATEMENT = (
    "Semantic Similarity Rating follows Maier et al., arXiv:2510.08338 (CC BY 4.0), App. A.4.3. The paper's six "
    "anchor sets are not published, so the anchor packs used here are local, independently authored and "
    "versioned (see pack ids in the manifest). Results reflect this pack, this embedder and these language "
    "models only; transfer to SME services, B2B software or enterprise buying committees is unvalidated."
)


class SyntheticViolation(ValueError):
    """An attempt to build a non-synthetic object or to move synthetic data toward a first-party sink."""


def _require_synthetic(obj: Any) -> None:
    if getattr(obj, "synthetic", None) is not True:
        raise SyntheticViolation(f"{type(obj).__name__}.synthetic must be True (synthetic data is never first-party)")


def stable_hash(obj: Any) -> str:
    """sha256 over canonical JSON (sorted keys, no whitespace); dataclasses are converted first."""
    return hashlib.sha256(canonical_json(obj).encode("utf-8")).hexdigest()


def canonical_json(obj: Any) -> str:
    return json.dumps(to_plain(obj), ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def to_plain(obj: Any) -> Any:
    """Recursively convert dataclasses / tuples / mappings to JSON-compatible plain values."""
    if is_dataclass(obj) and not isinstance(obj, type):
        return {f.name: to_plain(getattr(obj, f.name)) for f in fields(obj)}
    if isinstance(obj, Mapping):
        return {str(k): to_plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple, set, frozenset)):
        return [to_plain(v) for v in (sorted(obj) if isinstance(obj, (set, frozenset)) else obj)]
    return obj


# ── personas ───────────────────────────────────────────────────────────────────────────────────────────────
@dataclass(frozen=True)
class PersonaSpec:
    """A synthetic buyer archetype. Built from a sampling frame; contains no real person's data."""
    persona_id: str
    frame_id: str
    frame_version: str
    cell: str                                 # stratification cell, e.g. "professional_services/owner_partner"
    segment: str
    industry: str
    role: str
    firm_size: str                            # a label such as "11-50 staff"; not a measured market share
    decision_role: str                        # e.g. "economic buyer", "champion", "veto: security"
    budget_authority: str                     # e.g. "final", "influences", "none"
    stack: Tuple[str, ...] = ()
    pains: Tuple[str, ...] = ()
    purchase_criteria: Tuple[str, ...] = ()
    objections_to_probe: Tuple[str, ...] = ()
    constraints: Tuple[str, ...] = ()
    scenario_id: str = ""
    scenario_context: str = ""
    hypothetical_weight: Optional[float] = None      # stratification weight; ALWAYS hypothetical
    weight_label: str = "hypothetical (not a market-sampling weight)"
    seed: int = 0
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)
        if not self.persona_id:
            raise ValueError("persona_id required")

    @property
    def spec_hash(self) -> str:
        return stable_hash(self)


# ── sources and concepts ───────────────────────────────────────────────────────────────────────────────────
@dataclass(frozen=True)
class SourceSnapshot:
    """A public page as saved at ``fetched_at``. ``text`` is the visible text; ``sha256`` is of the raw bytes."""
    url: str
    fetched_at: str
    sha256: str
    text: str
    title: str = ""
    status_labels: Mapping[str, str] = field(default_factory=dict)   # feature -> label exactly as the page states
    business_object_ref: str = ""             # optional link to a BusinessObject id (not imported)
    synthetic: bool = True                    # the SNAPSHOT is real public text; the flag marks study-side use

    def __post_init__(self) -> None:
        _require_synthetic(self)
        for k, v in self.status_labels.items():
            if v not in STATUS_LABELS:
                raise ValueError(f"status label {v!r} for {k!r} not in {STATUS_LABELS}")


_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])|\n+")


def split_sentences(text: str) -> List[str]:
    return [s.strip() for s in _SENT_SPLIT.split(text) if s and s.strip()]


@dataclass(frozen=True)
class ConceptVariant:
    """One message variant shown to respondents. ``label`` is for analysts only and is NEVER shown to a model."""
    variant_id: str
    label: str
    headline: str = ""
    body: str = ""
    cta: str = ""
    brand: str = ""                           # shown only when the exposure config says so
    price_hypothesis: str = ""                # e.g. "USD 29/month (HYPOTHETICAL scenario)"
    price_is_hypothetical: bool = True
    competitor_context: str = ""              # shown only when the exposure config says so
    source_snapshot_hashes: Tuple[str, ...] = ()
    claims_status: Mapping[str, str] = field(default_factory=dict)  # claim -> planned/demo/available/...
    is_control: bool = False
    control_kind: str = ""
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)
        if not self.variant_id:
            raise ValueError("variant_id required")
        if self.price_hypothesis and not self.price_is_hypothetical:
            raise SyntheticViolation("a price in a synthetic concept is a HYPOTHESIS and must be flagged hypothetical")
        for v in self.claims_status.values():
            if v not in STATUS_LABELS:
                raise ValueError(f"claim status {v!r} not in {STATUS_LABELS}")

    def sentences(self) -> List[Tuple[str, str]]:
        """``[(sentence_id, text)]`` over headline, body and CTA; ids are stable (``<variant>.s<k>``)."""
        parts = [p for p in (self.headline, self.body, self.cta) if p and p.strip()]
        sents: List[str] = []
        for p in parts:
            got = split_sentences(p)
            sents.extend(got if got else [p.strip()])
        return [(f"{self.variant_id}.s{k + 1}", s) for k, s in enumerate(sents)]

    @property
    def content_hash(self) -> str:
        d = to_plain(self)
        d.pop("label", None)                  # relabelling never changes content identity
        return stable_hash(d)


@dataclass(frozen=True)
class QuestionConstruct:
    """One construct = one question = one anchor pack. Constructs never share a prompt or a pack."""
    name: str
    pack_construct: str
    question: str

    def __post_init__(self) -> None:
        if self.name not in CONSTRUCTS:
            raise ValueError(f"unknown construct {self.name!r}")
        if self.pack_construct != self.name:
            raise ValueError("a construct must use its own anchor pack (never reuse purchase_intent for trust)")


@dataclass(frozen=True)
class Recommendation:
    """A copy/demo/proof improvement HYPOTHESIS drawn from synthetic evidence. Never acted on automatically."""
    rec_id: str
    scope: str                                # niche or enterprise journey
    text: str
    page_text_cited: Tuple[str, ...]          # exact page sentences it refers to
    synthetic_evidence: Tuple[str, ...]       # response ids / theme ids / control results
    validation_plan: str = "interview and A/B test before any change"
    label: str = "HYPOTHESIS (synthetic, unvalidated)"
    requires_human_review: bool = True
    review_gate_status: str = "pending"
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)
        if self.requires_human_review is not True or self.review_gate_status != "pending":
            raise SyntheticViolation("a recommendation always requires human review and starts as 'pending'")
        if not self.page_text_cited or not self.synthetic_evidence:
            raise ValueError("a recommendation must cite page text and synthetic evidence")


class EmbedderMismatch(ValueError):
    """Two studies used different embedders (or revisions); comparing them needs an explicit, visible flag."""


# ── responses and distributions ────────────────────────────────────────────────────────────────────────────
@dataclass(frozen=True)
class SyntheticResponse:
    response_id: str
    persona_id: str
    variant_id: str
    construct: str
    text: str
    model_id: str
    params: Mapping[str, Any]
    seed: Optional[int]
    prompt_hash: str
    prompt_tokens: int = 0
    completion_tokens: int = 0
    latency_s: float = 0.0
    finish_reason: str = ""
    arm: str = "elicitation"                  # elicitation | dlr | flr
    status: str = "ok"                        # ok | refusal | unanchored | empty | error | skipped_budget
    exclude_reason: str = ""
    order_index: int = 0
    evidence_refs: Tuple[str, ...] = ()
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)

    @property
    def included(self) -> bool:
        return self.status == "ok"


@dataclass(frozen=True)
class SSRDistribution:
    response_id: str
    construct: str
    pmf: Tuple[float, ...]
    mean: float
    per_set_pmfs: Tuple[Tuple[float, ...], ...]
    variant: str                              # paper-cosine | ref-halfcosine
    epsilon: float
    temperature: float
    pack_id: str
    embedder_name: str
    degenerate_sets: int
    degenerate: bool
    arm: str = "ssr_paper"
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)


@dataclass(frozen=True)
class StudyManifest:
    study_id: str
    kind: str
    created_at: str
    seed: int
    models: Tuple[Mapping[str, Any], ...]
    generation_params: Mapping[str, Any]
    budget: Mapping[str, Any]
    anchor_pack_ids: Mapping[str, str]
    embedder_name: str
    embedder_revision: str
    ssr_arms: Tuple[Mapping[str, Any], ...]
    frame_hashes: Mapping[str, str]
    persona_count: int
    variant_hashes: Mapping[str, str]
    snapshot_refs: Tuple[Mapping[str, str], ...]
    constructs: Tuple[str, ...]
    prompt_template_version: str
    counts: Mapping[str, int] = field(default_factory=dict)
    cost: Mapping[str, Any] = field(default_factory=dict)
    untrusted_content_flags: Mapping[str, Any] = field(default_factory=dict)
    governance: Mapping[str, Any] = field(default_factory=dict)
    concept_split: Mapping[str, Any] = field(default_factory=dict)
    planted_order: Mapping[str, Any] = field(default_factory=dict)
    truncated: bool = False
    limitations: Tuple[str, ...] = ()
    fidelity_statement: str = FIDELITY_STATEMENT
    disclaimers: Tuple[str, ...] = DISCLAIMERS
    code_version: str = ""
    synthetic: bool = True
    schema_version: str = SCHEMA_VERSION

    def __post_init__(self) -> None:
        _require_synthetic(self)
        if not self.disclaimers:
            raise SyntheticViolation("a manifest must carry the standing disclaimers")


@dataclass(frozen=True)
class StudyResult:
    manifest: StudyManifest
    personas: Tuple[PersonaSpec, ...]
    variants: Tuple[ConceptVariant, ...]
    responses: Tuple[SyntheticResponse, ...]
    distributions: Tuple[SSRDistribution, ...]            # primary arm + comparison arms (all labelled)
    cells: Tuple[Mapping[str, Any], ...] = ()             # per (cell, construct, variant) aggregates
    comparisons: Tuple[Mapping[str, Any], ...] = ()       # per (cell, construct) variant comparison + CIs
    arm_ratings: Tuple[Mapping[str, Any], ...] = ()       # dlr / flr numeric ratings
    themes: Tuple[Mapping[str, Any], ...] = ()
    groundedness: Tuple[Mapping[str, Any], ...] = ()
    controls: Tuple[Mapping[str, Any], ...] = ()
    abstentions: Mapping[str, Any] = field(default_factory=dict)
    synthetic: bool = True

    def __post_init__(self) -> None:
        _require_synthetic(self)

    def to_dict(self) -> Dict[str, Any]:
        return to_plain(self)

    def evidence_ref(self) -> Dict[str, Any]:
        """A plain, serialisable reference that a later slice may cite as ``evidence_refs`` on an Opportunity or
        Experiment. It is a POINTER with the synthetic flag and the standing caveat, never a metric."""
        m = self.manifest
        return {"kind": "synthetic_study", "study_id": m.study_id, "manifest_sha256": stable_hash(m),
                "schema_version": SCHEMA_VERSION, "synthetic": True, "embedder": f"{m.embedder_name}@{m.embedder_revision}",
                "anchor_pack_ids": dict(m.anchor_pack_ids), "evidence_class": "synthetic-hypothesis",
                "caveat": DISCLAIMERS[0]}


